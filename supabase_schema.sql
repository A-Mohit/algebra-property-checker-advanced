-- Run in Supabase Dashboard > SQL Editor. Safe to re-run on an existing deployment.
-- Keep SUPABASE_SERVICE_ROLE_KEY and ROOT_ADMIN_PASSWORD only in Streamlit Secrets.
create table if not exists public.users (
  username text primary key,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

-- Upgrade an existing installation without deleting accounts or saved work.
alter table public.users add column if not exists email text;
alter table public.users add column if not exists status text not null default 'approved';
alter table public.users add column if not exists is_admin boolean not null default false;
create unique index if not exists users_email_unique on public.users(lower(email)) where email is not null;

create table if not exists public.theorems (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(username) on delete cascade,
  name text not null,
  variable_count integer not null check (variable_count in (2, 3)),
  lhs text not null,
  rhs text not null,
  created_at timestamptz not null default now(),
  unique (user_id, name, lhs, rhs)
);
create table if not exists public.algebras (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(username) on delete cascade,
  name text not null,
  elements jsonb not null,
  theta jsonb not null,
  phi jsonb not null,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);
create table if not exists public.password_resets (
  email text primary key,
  token_hash text not null,
  expires_at timestamptz not null
);
create index if not exists theorems_user_id_idx on public.theorems(user_id);
create index if not exists algebras_user_id_idx on public.algebras(user_id);

alter table public.users enable row level security;
alter table public.theorems enable row level security;
alter table public.algebras enable row level security;
alter table public.password_resets enable row level security;

-- Server-side Streamlit uses the service-role key only. Never expose it client-side.
grant usage on schema public to service_role;
grant select, insert, update, delete on table
  public.users, public.theorems, public.algebras, public.password_resets to service_role;
grant usage, select on all sequences in schema public to service_role;
alter default privileges in schema public
  grant select, insert, update, delete on tables to service_role;
alter default privileges in schema public
  grant usage, select on sequences to service_role;
