-- Run once in Supabase Dashboard > SQL Editor.
-- This application uses the service-role key only on the Streamlit server.
-- Never expose that key in frontend code or commit it to GitHub.
create table if not exists public.users (
  username text primary key,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.theorems (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(username) on delete cascade,
  name text not null,
  variable_count integer not null check (variable_count in (2, 3)),
  lhs text not null,
  rhs text not null,
  created_at timestamptz not null default now(),
  unique (user_id, name, lhs, rhs)
);

create table if not exists public.algebras (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(username) on delete cascade,
  name text not null,
  elements jsonb not null,
  theta jsonb not null,
  phi jsonb not null,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create index if not exists theorems_user_id_idx on public.theorems(user_id);
create index if not exists algebras_user_id_idx on public.algebras(user_id);

-- The app accesses these tables only from its server using the service-role key.
-- Enable RLS as defense in depth; service role bypasses RLS. Do not use the
-- service-role key in browser-side code or share it with users.
alter table public.users enable row level security;
alter table public.theorems enable row level security;
alter table public.algebras enable row level security;
